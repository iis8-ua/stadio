export const currentClient: Client = clients[0];

export function findClientByName(name: string): Client | undefined {
  const n = name.trim().toLowerCase();
  if (!n) return undefined;
  return (
    clients.find((c) => c.name.toLowerCase() === n) ??
    clients.find((c) => c.name.toLowerCase().startsWith(n)) ??
    clients.find((c) => c.name.toLowerCase().includes(n))
  );
}
